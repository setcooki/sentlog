/**
 * Sentlog public API. Singleton — one SDK instance per app session.
 *
 * Lifecycle:
 * ```
 * Sentlog.initialize(SentlogConfig(...))
 * Sentlog.startCapture()
 * // ...integrator captures user attention for 5-60 seconds...
 * val result = Sentlog.evaluate()
 * Sentlog.destroy()           // optional; initialize() also destroys
 * ```
 *
 * Threading:
 *  - [initialize] / [destroy] / [startCapture] / [cancel] /
 *    [getPermissions] / [getCapabilities] / [modelVersions] are
 *    synchronous and safe to call from any thread.
 *  - [evaluate] and [checkForUpdates] are `suspend` and switch to
 *    [Dispatchers.IO] internally.
 *  - The SDK's own audio thread is internal — integrators never see
 *    it.
 *
 * The SDK never requests permissions. If [PermissionState.Denied] is
 * surfaced via [getPermissions], the integrator is responsible for
 * requesting the relevant runtime permission before retrying.
 */
public object Sentlog {

    private val json = Json {
        ignoreUnknownKeys = true   // forward-compatible with new fields
        encodeDefaults    = true   // config defaults visible to native
        explicitNulls     = false
    }

    private var handle: Long = 0L
    private var audio: AudioCapture? = null
    private var vadStream: SileroVadStream? = null
    private var motion: MotionCapture? = null
    private var currentConfig: SentlogConfig? = null
    private var sileroModelBytes: ByteArray? = null
    private var aasistModelBytes: ByteArray? = null
    private var appContext: Context? = null
    private var userTelemetry: ((TelemetryEvent) -> Unit)? = null

    /** SDK version string. */
    public val version: String get() = NativeBridge.nativeVersion()

    /**
     * Initialise the SDK with [config]. If the SDK is already
     * initialised, the existing handle is destroyed first.
     *
     * Pass [context] to load bundled ML models (Silero VAD, AASIST-L
     * in a follow-up chunk) from the AAR's assets directory. If
     * [context] is null, the SDK falls back to its built-in
     * energy-based VAD — useful for tests that don't have an Android
     * Context.
     *
     * @throws IllegalArgumentException if the config fails validation
     *         (the message names the offending field).
     */
    @Synchronized
    public fun initialize(
        config: SentlogConfig,
        context: Context? = null,
        onTelemetry: ((TelemetryEvent) -> Unit)? = null,
    ) {
        if (handle != 0L) destroyLocked()

        userTelemetry = onTelemetry
        appContext = context?.applicationContext

        // Load the Silero VAD ONNX model bytes once and cache them.
        // The OrtSession is created later, per startCapture, so it can
        // be properly disposed at cancel/destroy.
        if (context != null && sileroModelBytes == null) {
            sileroModelBytes = try {
                context.assets.open(SILERO_MODEL_ASSET).use { it.readBytes() }
            } catch (_: Throwable) {
                null  // model missing → fall back to energy VAD
            }
        }

        // Same pattern for the AASIST-L liveness model. The .onnx file
        // is generated by tools/aasist-conversion/convert-aasist-l.py;
        // when absent (e.g. fresh clone before conversion has run) the
        // SDK falls back to the placeholder liveness in the pipeline.
        if (context != null && aasistModelBytes == null) {
            aasistModelBytes = try {
                context.assets.open(AASIST_MODEL_ASSET).use { it.readBytes() }
            } catch (_: Throwable) {
                null  // model missing → pipeline emits placeholder liveness
            }
        }
        val telemetryAdapter = onTelemetry?.let {
            object : TelemetryCallback() {
                override fun onTelemetry(eventJson: String?) {
                    if (eventJson == null) return
                    try {
                        val ev = json.decodeFromString(TelemetryEvent.serializer(), eventJson)
                        it(ev)
                    } catch (_: Exception) {
                        // Unknown event type — forward-compatibility: ignore.
                    }
                }
            }
        }

        val configJson = json.encodeToString(SentlogConfig.serializer(), config)
        val status = IntArray(1)
        val h = NativeBridge.nativeCreate(configJson, telemetryAdapter, status)
        if (h == 0L) {
            throw IllegalArgumentException(
                "SentlogConfig failed validation (status=${status[0]})"
            )
        }
        handle = h
        currentConfig = config
    }

    /**
     * Start audio capture. Throws [IllegalStateException] if the SDK
     * has not been initialised. Throws [SecurityException] if the
     * RECORD_AUDIO permission has not been granted.
     */
    @Synchronized
    public fun startCapture() {
        val h = requireHandle()
        appContext?.let { ctx ->
            if (permissionState(ctx, Manifest.permission.RECORD_AUDIO) != PermissionState.Granted) {
                throw SecurityException("RECORD_AUDIO permission not granted")
            }
        }
        val s = NativeBridge.nativeStartCapture(h)
        when (s) {
            NativeBridge.STATUS_OK -> {}
            NativeBridge.STATUS_ERR_INVALID_STATE ->
                throw IllegalStateException("startCapture called while not idle")
            else ->
                throw IllegalStateException("startCapture failed (status=$s)")
        }

        // A failed start must not leave the core stuck in Capturing.
        try {
            startCaptureStreams(h)
        } catch (t: Throwable) {
            stopCaptureStreams()
            NativeBridge.nativeCancel(h)
            throw t
        }
    }

    private fun startCaptureStreams(h: Long) {
        // Push the current audio input route so the C++ pipeline can
        // populate presence.audio_source. Without this push the route
        // stays UNKNOWN → audio_source = 0.0 in the result.
        appContext?.let { ctx ->
            val route = AudioRouteDetector.detect(ctx)
            NativeBridge.nativeSetAudioRoute(h, route)
        }

        // If we have the Silero model loaded, spin up an inference
        // session for this capture. ORT sessions are per-capture so
        // we can dispose cleanly at cancel/destroy.
        val silero = sileroModelBytes?.let { bytes ->
            try {
                SileroVadStream(bytes).also { vadStream = it }
            } catch (_: Throwable) {
                null  // ORT init failed → fall back to energy VAD
            }
        }

        audio = AudioCapture(
            pushFrame = { samples, n ->
                NativeBridge.nativePushAudioFrame(h, samples, n)
            },
            vad = silero,
            pushVad = silero?.let {
                { startSample, numSamples, prob ->
                    NativeBridge.nativePushVadFrame(h, startSample, numSamples, prob)
                }
            },
        ).also { it.start() }

        // Phase 3c: motion-coherence. Opt-in via config —
        // use_motion_sensors must be true AND the integrator must
        // have ensured no extra runtime permission is needed (none
        // are required on Android for accel/gyro). If the device
        // doesn't expose accelerometer or gyroscope, MotionCapture
        // silently no-ops; the pipeline emits no presence.motion.
        appContext?.let { ctx ->
            if (currentConfig?.useMotionSensors == true) {
                motion = MotionCapture(ctx) { ts, ax, ay, az, gx, gy, gz ->
                    NativeBridge.nativePushMotionFrame(h, ts, ax, ay, az, gx, gy, gz)
                }.also { it.start() }
            }
        }
    }

    private fun stopCaptureStreams() {
        audio?.stop()
        audio = null
        vadStream?.close()
        vadStream = null
        motion?.stop()
        motion = null
    }

    /**
     * Stop capture and run the evaluation pipeline. Returns when the
     * pipeline completes.
     */
    public suspend fun evaluate(): SentlogResult = withContext(Dispatchers.IO) {
        val deferred = CompletableDeferred<SentlogResult>()
        // The whole synchronous critical section runs under the
        // singleton monitor so a concurrent cancel() / destroy() /
        // initialize() can't free the C handle while AASIST + whisper
        // are snapshotting + pushing into it, or while sentlog_evaluate
        // is running. The C ABI guarantees the result callback fires
        // synchronously from inside sentlog_evaluate (c_api.cpp), so
        // `deferred` is already completed by the time we exit the
        // synchronized block and `await` returns immediately.
        synchronized(this@Sentlog) {
            val h = requireHandle()
            stopCaptureStreams()

            runAasistAndPushLiveness(h)
            runWhisperAndPushTranscript(h)

            val cb = object : ResultCallback() {
                override fun onResult(status: Int, resultJson: String?) {
                    if (status != NativeBridge.STATUS_OK || resultJson == null) {
                        deferred.completeExceptionally(
                            IllegalStateException("evaluate failed (status=$status)")
                        )
                        return
                    }
                    try {
                        deferred.complete(
                            json.decodeFromString(SentlogResult.serializer(), resultJson)
                        )
                    } catch (e: Exception) {
                        deferred.completeExceptionally(e)
                    }
                }
            }
            // nativeEvaluate fires cb synchronously even on failure
            // — no "kickoff failed without cb" branch needed.
            NativeBridge.nativeEvaluate(h, cb)
        }
        deferred.await()
    }

    /**
     * Cancel an in-progress capture. Safe to call any time. A running
     * evaluation isn't interrupted: this waits for it to finish.
     */
    @Synchronized
    public fun cancel() {
        if (handle == 0L) return
        stopCaptureStreams()
        NativeBridge.nativeCancel(handle)
    }

    /**
     * Current permission state. Without the Context passed to
     * [initialize] the SDK can't look, and reports `Prompt`. A permission
     * not granted reports `Prompt` too: Android only tells an Activity
     * whether the user has denied it.
     */
    @Synchronized
    public fun getPermissions(): Permissions {
        val h = requireHandle()
        val js = NativeBridge.nativeGetPermissions(h)
            ?: error("nativeGetPermissions returned null")
        val base = json.decodeFromString(Permissions.serializer(), js)
        val ctx = appContext ?: return base
        return Permissions(
            microphone = permissionState(ctx, Manifest.permission.RECORD_AUDIO),
            // Accelerometer and gyroscope need no runtime permission.
            motion = if (base.motion == PermissionState.NotRequested) base.motion
                     else PermissionState.Granted,
            camera = if (base.camera == PermissionState.NotRequested) base.camera
                     else permissionState(ctx, Manifest.permission.CAMERA),
        )
    }

    private fun permissionState(ctx: Context, permission: String): PermissionState =
        if (ctx.checkPermission(permission, Process.myPid(), Process.myUid()) ==
            PackageManager.PERMISSION_GRANTED
        ) PermissionState.Granted else PermissionState.Prompt

    /** Current capability detection; never throws. */
    @Synchronized
    public fun getCapabilities(): Capabilities {
        val h = requireHandle()
        val js = NativeBridge.nativeGetCapabilities(h)
            ?: error("nativeGetCapabilities returned null")
        return json.decodeFromString(Capabilities.serializer(), js)
    }

    /** Versions of loaded models. */
    @Synchronized
    public fun modelVersions(): ModelVersions {
        val h = requireHandle()
        val js = NativeBridge.nativeModelVersions(h)
            ?: error("nativeModelVersions returned null")
        return json.decodeFromString(ModelVersions.serializer(), js)
    }

    /**
     * Check for an OTA model update. Integrator-triggered; never
     * autonomous. Fetches the configured manifest URL over HTTPS and
     * verifies the Ed25519 signature against the two pinned pubkeys
     * — both as configured in [SentlogConfig] (when overridden) or
     * the Sentlog-published defaults.
     *
     * Throws [IllegalStateException] on fetch failure (DNS, HTTP
     * non-2xx, oversize response) or verification failure.
     */
    public suspend fun checkForUpdates(): UpdateResult =
        withContext(Dispatchers.IO) {
            val cfg = currentConfig
                ?: error("checkForUpdates before initialize")
            val url = cfg.manifestUrl ?: DEFAULT_MANIFEST_URL
            val bytes = fetchManifestHttps(url)
            checkForUpdates(String(bytes, Charsets.UTF_8))
        }

    /**
     * Check for an OTA model update by verifying a pre-fetched
     * signed-manifest envelope (wire format in spec §5.1). Use this
     * overload when integrators want to drive the fetch itself
     * (custom HTTP client, caching, mocking in tests). The no-arg
     * overload above is the common path.
     *
     * On verification failure throws [IllegalStateException] carrying
     * the failure-mode string from the envelope's `error` field.
     */
    public suspend fun checkForUpdates(manifestJson: String): UpdateResult =
        withContext(Dispatchers.IO) {
            val deferred = CompletableDeferred<UpdateResult>()
            val cb = object : UpdateCallback() {
                override fun onUpdate(status: Int, updateJson: String?) {
                    if (updateJson == null) {
                        deferred.completeExceptionally(
                            IllegalStateException(
                                "checkForUpdates failed (status=$status)"))
                        return
                    }
                    try {
                        val parsed = json.decodeFromString(
                            UpdateResult.serializer(), updateJson)
                        if (status != NativeBridge.STATUS_OK) {
                            deferred.completeExceptionally(
                                IllegalStateException(
                                    "checkForUpdates verify failed: " +
                                    (parsed.error ?: "unknown")))
                            return
                        }
                        deferred.complete(parsed)
                    } catch (e: Exception) {
                        deferred.completeExceptionally(e)
                    }
                }
            }
            val manifestBytes = manifestJson.toByteArray(Charsets.UTF_8)
            // Under the monitor so destroy() can't free the handle during
            // the call. The callback fires synchronously inside it.
            val initialStatus = synchronized(this@Sentlog) {
                NativeBridge.nativeCheckForUpdates(requireHandle(), manifestBytes, cb)
            }
            if (initialStatus != NativeBridge.STATUS_OK &&
                initialStatus != NativeBridge.STATUS_ERR_MANIFEST_VERIFY) {
                throw IllegalStateException(
                    "checkForUpdates kickoff failed (status=$initialStatus)")
            }
            deferred.await()
        }

    /**
     * Phase 5b: push one face-affect frame computed by the platform-
     * side affect head (the integrator's MediaPipe Face Mesh +
     * affect-head MLP). Raw landmarks never reach the SDK — only the
     * derived (valence, arousal, FAU) values cross the boundary, per
     * the structural privacy guarantee in spec §5.3.
     *
     * `valence` is [-1, 1]; `arousal` is [0, 1]; `dominantFauCsv` is a
     * comma-separated list of activated FAU codes (e.g. "AU6,AU12"),
     * or null when no FAU was dominant in this frame.
     *
     * Frames must be pushed between [startCapture] and [evaluate];
     * lifecycle violation throws [IllegalStateException]. The SDK
     * aggregates buffered frames into `Affect{valence, arousal,
     * dominant_fau}` in the result and contributes to engagement
     * via the `engagement.face` scoring weight.
     */
    @Synchronized
    public fun pushFaceFrame(
        timestampNs: Long,
        valence: Float,
        arousal: Float,
        dominantFauCsv: String? = null,
    ) {
        val h = requireHandle()
        val s = NativeBridge.nativePushFaceFrame(
            h, timestampNs, valence, arousal, dominantFauCsv)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalStateException(
                "pushFaceFrame failed (status=$s) — call between " +
                "startCapture and evaluate")
        }
    }

    /**
     * Phase 4g-ii: register (or clear, with `encoder = null`) the
     * audio encoder invoked once per evaluate when an AudioClip-
     * bearing forwarder is configured. The encoder receives 16 kHz
     * mono float PCM + sample rate; returns the encoded bytes
     * (Opus typically) or null on failure.
     *
     * Most integrators don't call this directly — `OpusAudioEncoder`
     * (lands in 4g-ii Android) wraps MediaCodec with the right
     * format setup.
     */
    @Synchronized
    public fun setAudioEncoder(
        encoder: ((pcmSamples: FloatArray, sampleRateHz: Int) -> ByteArray?)?,
        codecName: String? = null,
    ) {
        val h = requireHandle()
        if (encoder == null) {
            val s = NativeBridge.nativeSetAudioEncoder(h, null, null)
            if (s != NativeBridge.STATUS_OK) {
                throw IllegalStateException("setAudioEncoder failed (status=$s)")
            }
            return
        }
        require(!codecName.isNullOrEmpty()) {
            "setAudioEncoder: codecName required when encoder is non-null"
        }
        val adapter = object : AudioEncoderCallback() {
            override fun onEncode(pcmSamples: FloatArray, sampleRateHz: Int) =
                encoder(pcmSamples, sampleRateHz)
        }
        val s = NativeBridge.nativeSetAudioEncoder(h, adapter, codecName)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalStateException("setAudioEncoder failed (status=$s)")
        }
    }

    /**
     * Phase 4h-ii: register (or clear, with `provider = null`) the
     * RFC 3161 TSA provider invoked after envelope signing when
     * `SentlogConfig.tsaEndpoint` is set. The provider receives the
     * proof.proofValue bytes to hash, the TSA URL, and a timeout;
     * returns the DER TimeStampResp bytes or null on failure.
     *
     * Most integrators don't call this directly — `RfcTsaProvider`
     * (lands in 4h-ii Android) handles the SHA-256 + ASN.1
     * TimeStampReq + HTTPS POST.
     */
    @Synchronized
    public fun setTsaProvider(
        provider: ((
            toHashBytes: ByteArray,
            tsaEndpointUrl: String,
            timeoutMs: Int,
        ) -> ByteArray?)?,
    ) {
        val h = requireHandle()
        val adapter = provider?.let {
            object : TsaProviderCallback() {
                override fun onTsaRequest(
                    toHashBytes: ByteArray,
                    tsaEndpointUrl: String,
                    timeoutMs: Int,
                ): ByteArray? = it(toHashBytes, tsaEndpointUrl, timeoutMs)
            }
        }
        val s = NativeBridge.nativeSetTsaProvider(h, adapter)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalStateException("setTsaProvider failed (status=$s)")
        }
    }

    /**
     * Phase 5e: push the most recent device-attestation token (from
     * Play Integrity). The SDK records the token + type as
     * `credentialSubject.device_attestation` on every dispatched
     * envelope and promotes `evidence_grade` from `DeviceUnattested`
     * to `DeviceAttested`. Never demotes from `EnclaveSigned` (set
     * by hardware-backed signing in 7c-i).
     *
     * Pass `tokenBytes = null` to clear a previously-pushed
     * attestation. Attestation lifetime is integrator-managed; if
     * yours expire, push a fresh one before the next evaluate.
     *
     * Today the integrator wires Play Integrity directly. A bundled
     * `PlayIntegrityAttester` helper (Google Play Services dep) is
     * planned for 5e-ii.
     */
    @Synchronized
    public fun setDeviceAttestation(
        tokenBytes: ByteArray?,
        attestationType: String? = null,
    ) {
        val h = requireHandle()
        val s = NativeBridge.nativeSetDeviceAttestation(
            h, tokenBytes, attestationType)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalArgumentException(
                "setDeviceAttestation rejected (status=$s) — when " +
                "tokenBytes is non-null, attestationType must be non-empty")
        }
    }

    /**
     * Phase 4d: register the Ed25519 signing key the SDK uses to
     * populate the W3C VC 2.0 envelope's `proof` block.
     * `secretKey` is the 64-byte RFC 8032 seed||pubkey concatenation;
     * the integrator obtains it from libsodium / a hardware-backed
     * KeyStore. Throws [IllegalArgumentException] on wrong-length keys.
     *
     * Without a registered key, envelopes are emitted unsigned (no
     * proof block). Hardware-backed signing lands in Phase 7 with
     * `ecdsa-jcs-2019`.
     */
    @Synchronized
    public fun setSigningKey(secretKey: ByteArray, verificationMethod: String) {
        val h = requireHandle()
        val s = NativeBridge.nativeSetSigningKey(h, secretKey, verificationMethod)
        when (s) {
            NativeBridge.STATUS_OK -> {}
            NativeBridge.STATUS_ERR_INVALID_CONFIG ->
                throw IllegalArgumentException(
                    "setSigningKey rejected: key must be 64 bytes (RFC 8032 seed||pubkey)")
            else ->
                throw IllegalStateException("setSigningKey failed (status=$s)")
        }
    }

    /**
     * Phase 4d: register (or clear, with `null`) the per-handle
     * envelope dispatcher. The lambda fires once per configured
     * forwarder after [evaluate], for sinks other than `local_queue`
     * (the C++ core writes those to file). The lambda runs on the
     * SDK's I/O thread; long-running work (HTTP POSTs, etc.) should
     * hand off to the integrator's own scheduler.
     *
     * Same shape as the iOS counterpart. Exceptions thrown inside
     * the lambda are caught + logged by the JNI trampoline so the
     * dispatch loop survives.
     */
    @Synchronized
    public fun setEnvelopeDispatcher(
        handler: ((forwarderName: String,
                   sinkKind: String,
                   sinkJson: String,
                   envelopeJson: String) -> Unit)?,
    ) {
        val h = requireHandle()
        val adapter = handler?.let {
            object : EnvelopeDispatcher() {
                override fun onEnvelope(
                    forwarderName: String,
                    sinkKind: String,
                    sinkJson: String,
                    envelopeJson: String,
                ) {
                    it(forwarderName, sinkKind, sinkJson, envelopeJson)
                }
            }
        }
        val s = NativeBridge.nativeSetEnvelopeDispatcher(h, adapter)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalStateException("setEnvelopeDispatcher failed (status=$s)")
        }
    }

    /**
     * Phase 7c: register (or clear, with `null`) the hardware signer.
     * The `signer` lambda receives the JCS-canonical envelope bytes
     * and returns the raw signature — ASN.1/DER for ECDSA-P256 (≤72
     * bytes), 64 bytes for Ed25519. Return `null` on signing failure
     * (KeyStore unavailable, biometric prompt denied, etc.); the SDK
     * then falls back to the software Ed25519 key registered via
     * [setSigningKey] and emits a `HardwareSigningUnavailable`
     * telemetry event — unless [SentlogConfig.hardwareSigningRequired]
     * is true, in which case the envelope is dropped with a
     * `ForwarderOutcome=dropped` telemetry event.
     *
     * `cryptosuite` must be either `"ecdsa-jcs-2019"` (Secure Enclave
     * on iOS / KeyStore ECDSA-P256 on Android API 31-32) or
     * `"eddsa-jcs-2022"` (Android KeyStore Ed25519, API 33+).
     * `verificationMethod` is written into proof.verificationMethod —
     * typically a `did:key:` URI the verifier resolves to the public
     * key.
     *
     * The integrator owns the actual KeyStore key today; a
     * SDK-provided `KeyStoreSigner` helper lands in Phase 7.5.
     */
    @Synchronized
    public fun setHardwareSigner(
        signer: ((messageBytes: ByteArray) -> ByteArray?)?,
        cryptosuite: String = "ecdsa-jcs-2019",
        verificationMethod: String = "",
    ) {
        val h = requireHandle()
        val adapter = signer?.let {
            object : HardwareSignerCallback() {
                override fun onSign(messageBytes: ByteArray): ByteArray? =
                    it(messageBytes)
            }
        }
        val s = NativeBridge.nativeSetHardwareSigner(
            h,
            adapter,
            if (signer == null) null else cryptosuite,
            if (signer == null) null else verificationMethod)
        if (s != NativeBridge.STATUS_OK) {
            throw IllegalStateException("setHardwareSigner failed (status=$s)")
        }
    }

    /**
     * Phase 7.5 convenience overload: register a SDK-provided
     * [KeyStoreSigner] as the hardware signer. Wires the signer's
     * sign closure, cryptosuite (always `"ecdsa-jcs-2019"` for the
     * P-256 path), and `did:key:` verificationMethod in one call.
     */
    public fun setHardwareSigner(signer: KeyStoreSigner) {
        setHardwareSigner(
            signer.sign,
            cryptosuite        = "ecdsa-jcs-2019",
            verificationMethod = signer.verificationMethod)
    }

    /**
     * Drain a local-queue forwarder file (NDJSON). For each envelope
     * in the file, [drain] is invoked; return `true` to remove the
     * envelope from the queue, `false` to keep it for a later drain.
     * Returns the number of envelopes delivered.
     *
     * Safe to call without a live SDK handle — the file I/O doesn't
     * need one. The C ABI takes a handle for forward-compatibility
     * with future telemetry; today it's ignored.
     */
    public fun drainQueue(path: String, drain: (String) -> Boolean): Int {
        // sentlog_drain_queue ignores the handle, and reading it here
        // would race destroy().
        return NativeBridge.nativeDrainQueue(0L, path,
            object : DrainCallback() {
                override fun onEnvelope(envelopeJson: String): Boolean =
                    drain(envelopeJson)
            })
    }

    /**
     * Release all SDK resources. Safe to call multiple times. After
     * destroy, the SDK must be re-initialised before further use.
     */
    @Synchronized
    public fun destroy() {
        destroyLocked()
    }

    // --- internal helpers ---

    private fun destroyLocked() {
        stopCaptureStreams()
        if (handle != 0L) {
            NativeBridge.nativeDestroy(handle)
            handle = 0L
        }
        userTelemetry = null
        currentConfig = null
    }

    private fun requireHandle(): Long {
        val h = handle
        check(h != 0L) { "Sentlog is not initialised — call Sentlog.initialize(...) first" }
        return h
    }

    /** Run AASIST-L over the captured audio if the model is bundled.
     *  Safe to call always — if the model file isn't present, this is
     *  a no-op and the pipeline emits the placeholder liveness. */
    private fun runAasistAndPushLiveness(h: Long) {
        val modelBytes = aasistModelBytes ?: return
        val capacity = AasistLivenessRunner.TARGET_SAMPLES
        val buf = FloatArray(capacity)
        val n = NativeBridge.nativeSnapshotAudio(h, buf)
        if (n <= 0) return
        val audioSlice = if (n == capacity) buf else buf.copyOfRange(0, n)
        try {
            AasistLivenessRunner(modelBytes).use { runner ->
                val result = runner.infer(audioSlice)
                NativeBridge.nativePushLivenessResult(
                    h, result.score, result.replayRisk, result.syntheticRisk
                )
            }
        } catch (_: Throwable) {
            // ORT failure shouldn't fail the whole evaluation — the
            // pipeline carries the placeholder liveness instead and
            // model_versions.liveness flags it.
        }
    }

    /** Run whisper.cpp over the captured audio if the model is
     *  bundled. Safe to call always — when the asset isn't present
     *  this is a no-op and the C++ pipeline emits the placeholder
     *  transcript. Pushes the result via sentlog_push_transcript so
     *  Pipeline::run populates the result's transcript block from it.
     *
     *  Whisper takes a few seconds per call. evaluate() runs on
     *  Dispatchers.IO already, so this stays inline.
     */
    private fun runWhisperAndPushTranscript(h: Long) {
        val ctx = appContext ?: return
        // Snapshot the full ring. Bigger than AASIST-L's
        // 4 s window because whisper transcribes everything that was said.
        val capacity = WHISPER_MAX_SAMPLES
        val buf = FloatArray(capacity)
        val n = NativeBridge.nativeSnapshotAudio(h, buf)
        if (n <= 0) return
        val audioSlice = if (n == capacity) buf else buf.copyOfRange(0, n)
        try {
            WhisperRunner.loadIfAvailable(ctx)?.use { runner ->
                val json = runner.transcribe(audioSlice) ?: return
                NativeBridge.nativePushTranscript(h, json)
            }
        } catch (_: Throwable) {
            // whisper.cpp failure leaves the placeholder transcript in
            // place — model_versions.asr flags that nothing real ran.
        }
    }

    /** Asset name of the bundled Silero VAD ONNX model. */
    private const val SILERO_MODEL_ASSET: String = "silero_vad.onnx"
    /** Asset name of the bundled AASIST-L liveness ONNX model. */
    private const val AASIST_MODEL_ASSET: String = "aasist_l.onnx"
    /** Whisper transcribes everything captured — matches the ring
     *  buffer size in shared/src/internal/state.h. */
    private const val WHISPER_MAX_SAMPLES: Int = 1_048_576

    /** Sentlog-published manifest URL. Placeholder until the v1.0
     *  manifest-publishing infrastructure goes live. Integrators
     *  shipping OTA today override via [SentlogConfig.manifestUrl] +
     *  [SentlogConfig.manifestPubkeys] (paired override). */
    private const val DEFAULT_MANIFEST_URL: String =
        "https://sentlog.cooki.me/manifest/v1.json"

    /** Cap response body to keep a malicious or misconfigured manifest
     *  endpoint from exhausting heap. Real manifests are <2 KB. */
    private const val MANIFEST_MAX_BYTES: Int = 64 * 1024
    private const val MANIFEST_TIMEOUT_MS: Int = 10_000

    /** HTTPS-only manifest fetch using java.net stdlib — no extra
     *  dependency. Throws [IllegalStateException] on non-2xx, oversize,
     *  non-HTTPS, or timeout. */
    private fun fetchManifestHttps(url: String): ByteArray {
        if (!url.startsWith("https://")) {
            throw IllegalStateException("manifest URL must be https")
        }
        val conn = (java.net.URL(url).openConnection()
            as java.net.HttpURLConnection).apply {
            connectTimeout = MANIFEST_TIMEOUT_MS
            readTimeout    = MANIFEST_TIMEOUT_MS
            requestMethod  = "GET"
            doInput        = true
            instanceFollowRedirects = false
        }
        try {
            val code = conn.responseCode
            if (code !in 200..299) {
                throw IllegalStateException(
                    "manifest fetch HTTP $code from $url")
            }
            conn.inputStream.use { stream ->
                val out = java.io.ByteArrayOutputStream()
                val buf = ByteArray(8 * 1024)
                while (true) {
                    val n = stream.read(buf)
                    if (n < 0) break
                    if (out.size() + n > MANIFEST_MAX_BYTES) {
                        throw IllegalStateException(
                            "manifest oversize (>$MANIFEST_MAX_BYTES bytes)")
                    }
                    out.write(buf, 0, n)
                }
                return out.toByteArray()
            }
        } finally {
            conn.disconnect()
        }
    }
